#!/usr/bin/env python3
"""Docs-only: scans src/assets/ and writes the three data files behind
the showcase's (index.html) library pages. Re-run after adding, renaming or removing
a logo, icon or illustration (standard library only, no installs):

    python3 src/docs/build-asset-manifests.py

Each output is a plain <script> (window.DOCS_*_MANIFEST = [...]) rather than
JSON so the page still works opened straight from disk (file://), where
fetch() of a local JSON file is blocked.

logo-manifest.js — src/assets/logos/ (Logo library page)
  {name, dir, family, dark, usage, record, formats: {png: {path, bytes, w, h}, svg: {path, bytes, raster}}}
  family - the program a logo belongs to (None for badges): the file name up
           to its first "logo"/"badge"/"icon"/... word, minus trailing
           variant words (rgb, white, stacked, ...).
  dark   - light artwork (white/reverse variants) that needs a dark tile.
  usage / record - the file's "Usage Restrictions" value and record id in
           the CSA Digital Asset Repository (Airtable), read from
           logo-usage.json next to this script ("files" is a snapshot of the
           Airtable table; "overrides" are local decisions that win over it).
  raster - an .svg that only wraps an embedded bitmap (<image>), so it
           won't scale like a true vector.
  The *-cropped.png twins are skipped: trimmed copies of files already listed.

icon-manifest.js — src/assets/icons/ (Icon library page)
  {name, chips: [style...], png: [style...], glyphs: [color...]}
  chips  - chip styles that exist as icons/<name>[-<style>].svg; "default" is
           the plain <name>.svg (Monochrome). Paths follow from the name, so
           only the list of styles is stored.
  png    - chip styles that also ship as .png.
  glyphs - color folders (icons/<color>/<name>-<color>.svg) holding the
           glyph-only version of this icon.
  Top-level copies of a glyph (e.g. icons/calendar-b500.svg, identical to
  icons/b500/calendar-b500.svg and used by the Badges demo) are skipped.

illustration-manifest.js — src/assets/illustrations/ (Illustration library page)
  {scene, variants: [{suffix, path, bytes, w, h}]}
  suffix - white-bg | light-blue-bg | dark-blue-bg (pre-composited onto that
           backdrop), light | dark (transparent), or an alternate name.
"""
import json, os, re, struct

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, '..', 'assets')


def png_size(path):
    with open(path, 'rb') as f:
        head = f.read(24)
    if head[12:16] != b'IHDR':
        return {}
    w, h = struct.unpack('>II', head[16:24])
    return {'w': w, 'h': h}


def write(name, var, data, what):
    out = os.path.join(HERE, name)
    with open(out, 'w') as fh:
        fh.write('/* Generated by build-asset-manifests.py - do not edit by hand. */\n')
        fh.write(f'window.{var} = ' + json.dumps(data, separators=(',', ':')) + ';\n')
    print(f'Wrote {len(data)} {what} to {os.path.relpath(out)}')


# ---------------------------------------------------------------- logos
def build_logos():
    root = os.path.join(ASSETS, 'logos')
    stop = {'logo', 'badge', 'icon', 'lettermark', 'primary', 'acronym', 'orb'}
    variant = {'rgb', 'cmyk', 'grayscale', 'white', 'reverse', 'colors', 'horizontal', 'stacked',
               'simplified', 'w', 'bottom', 'text', 'small', 'large', 'internal', 'clear', 'space', 'neu', 'mark'}
    badge_names = {'csa-chapter-of-excellence'}  # badges whose file name doesn't say "badge"

    def family(name):
        t = name.split('-')
        if 'badge' in t or name in badge_names:
            return None
        out = []
        for x in t:
            if x in stop:
                break
            out.append(x)
        while out and out[-1] in variant:
            out.pop()
        return '-'.join(out) or t[0]

    try:
        with open(os.path.join(HERE, 'logo-usage.json')) as fh:
            usage_doc = json.load(fh)
        usage = usage_doc.get('files', {})
        for k, v in usage_doc.get('overrides', {}).items():
            usage[k] = {**usage.get(k, {}), **v}
    except FileNotFoundError:
        usage = {}

    items = {}
    for dp, _, files in sorted(os.walk(root)):
        for f in sorted(files):
            name, ext = os.path.splitext(f)
            ext = ext.lower().lstrip('.')
            if ext not in ('png', 'svg') or name.endswith('-cropped'):
                continue
            rel = os.path.relpath(os.path.join(dp, f), root).replace(os.sep, '/')
            d = os.path.dirname(rel)
            key = (d + '/' if d else '') + name
            if key not in items:
                t = name.split('-')
                u = usage.get(key, {})
                items[key] = {'name': name, 'dir': d, 'family': family(name),
                              'dark': 'white' in t or 'reverse' in t,
                              'usage': u.get('usage'), 'record': u.get('record'), 'formats': {}}
            fmt = {'path': rel, 'bytes': os.path.getsize(os.path.join(dp, f))}
            if ext == 'png':
                fmt.update(png_size(os.path.join(dp, f)))
            else:
                with open(os.path.join(dp, f), 'rb') as fh:
                    fmt['raster'] = b'<image' in fh.read()
            items[key]['formats'][ext] = fmt
    write('logo-manifest.js', 'DOCS_LOGO_MANIFEST', list(items.values()), 'logos')


# ---------------------------------------------------------------- icons
def build_icons():
    root = os.path.join(ASSETS, 'icons')
    styles = ['white', 'light-blue', 'csa-blue', 'yellow-orange', 'red-orange']  # + "default"
    folders = sorted(d for d in os.listdir(root) if os.path.isdir(os.path.join(root, d)))
    glyph_suffix = re.compile(r'-(%s)$' % '|'.join(map(re.escape, folders)))
    style_suffix = re.compile(r'-(%s)$' % '|'.join(map(re.escape, styles)))

    icons = {}
    for f in sorted(os.listdir(root)):
        name, ext = os.path.splitext(f)
        ext = ext.lower().lstrip('.')
        if ext not in ('svg', 'png') or not os.path.isfile(os.path.join(root, f)):
            continue
        if glyph_suffix.search(name):  # stray top-level copy of a glyph-folder file
            continue
        m = style_suffix.search(name)
        base, style = (name[:m.start()], m.group(1)) if m else (name, 'default')
        it = icons.setdefault(base, {'name': base, 'chips': [], 'png': [], 'glyphs': []})
        (it['chips'] if ext == 'svg' else it['png']).append(style)
    for color in folders:
        for f in sorted(os.listdir(os.path.join(root, color))):
            name, ext = os.path.splitext(f)
            if ext.lower() != '.svg' or not name.endswith('-' + color):
                continue
            base = name[:-len(color) - 1]
            icons.setdefault(base, {'name': base, 'chips': [], 'png': [], 'glyphs': []})['glyphs'].append(color)
    order = ['default'] + styles
    for it in icons.values():
        it['chips'].sort(key=order.index)
        it['png'].sort(key=order.index)
    write('icon-manifest.js', 'DOCS_ICON_MANIFEST', sorted(icons.values(), key=lambda x: x['name']), 'icons')


# ---------------------------------------------------------- illustrations
def build_illustrations():
    root = os.path.join(ASSETS, 'illustrations')
    # Longest first, so "dark-blue-bg" wins over "dark-blue" and "dark".
    suffixes = ['light-blue-bg', 'dark-blue-bg', 'white-bg', 'light-blue', 'dark-blue', 'white', 'light', 'dark']
    pat = re.compile(r'^(.*?)-(%s)$' % '|'.join(suffixes))
    order = ['white-bg', 'light-blue-bg', 'dark-blue-bg', 'light', 'dark', 'white', 'light-blue', 'dark-blue']
    scenes = {}
    for f in sorted(os.listdir(root)):
        name, ext = os.path.splitext(f)
        if ext.lower() not in ('.png', '.svg', '.jpg'):
            continue
        m = pat.match(name)
        scene, suffix = (m.group(1), m.group(2)) if m else (name, '')
        v = {'suffix': suffix, 'path': f, 'bytes': os.path.getsize(os.path.join(root, f))}
        if ext.lower() == '.png':
            v.update(png_size(os.path.join(root, f)))
        scenes.setdefault(scene, {'scene': scene, 'variants': []})['variants'].append(v)
    for s in scenes.values():
        s['variants'].sort(key=lambda v: order.index(v['suffix']) if v['suffix'] in order else 99)
    write('illustration-manifest.js', 'DOCS_ILLUSTRATION_MANIFEST', sorted(scenes.values(), key=lambda s: s['scene']), 'illustration scenes')


build_logos()
build_icons()
build_illustrations()
